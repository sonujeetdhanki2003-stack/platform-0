export const CH_NAMES = ['Platform 0', 'The Subway', 'The Last Local'];
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
export class Archive {
  constructor(A) { // A: { save, writeSave, show, $ }
    this.A = A; this.open = null; this.tab = 0;
  }
  get save() { const s = this.A.save(); if (!Array.isArray(s.archive)) s.archive = []; if (!Array.isArray(s.archiveSeen)) s.archiveSeen = []; return s; }
  has(id) { return this.save.archive.includes(id); }
  count() { const ids = new Set(ARCHIVE.map(e => e.id)); return this.save.archive.filter(i => ids.has(i)).length; }
  total() { return ARCHIVE.length; }
  unseen() { const s = this.save; return s.archive.filter(i => !s.archiveSeen.includes(i)).length; }
  // a right turn-back on an anomaly: returns the entry if it is new
  unlock(id) { const e = ARCHIVE.find(x => x.id === id); if (!e || this.has(id)) return null; this.save.archive.push(id); this.A.writeSave(); return e; }
  label() { const n = this.count(), u = this.unseen(); return `Archive ${n}/${this.total()}`; }
  render() {
    const s = this.save, el = this.A.$('archList'), tabs = this.A.$('archTabs'), rd = this.A.$('archRead');
    this.A.$('archCount').textContent = `${this.count()} / ${this.total()} found`;
    tabs.innerHTML = CH_NAMES.map((nm, i) => { const all = ARCHIVE.filter(e => e.ch === i + 1), got = all.filter(e => s.archive.includes(e.id)).length; return `<button class="archTab${i === this.tab ? ' on' : ''}" data-tab="${i}"><span>${i + 1} · ${nm}</span><small>${got} / ${all.length}</small></button>`; }).join('');
    const e = this.open && ARCHIVE.find(x => x.id === this.open);
    if (e) { // the reader: one note, big, with a way back to the list
      const k = ARCHIVE.filter(x => x.ch === e.ch).indexOf(e) + 1;
      rd.innerHTML = `<div class="archRH"><button class="archBackList" aria-label="All entries">‹</button><div class="archRT">${esc(e.t)}${e.h ? ' <i>HIDDEN</i>' : ''}</div></div><div class="archRM">Chapter ${e.ch} · ${CH_NAMES[e.ch - 1]} · ${String(k).padStart(2, '0')}</div><div class="archNote">${esc(e.n).replace(/\n/g, '<br>')}</div>`;
      rd.style.display = 'block'; el.style.display = 'none'; rd.scrollTop = 0; return; }
    rd.style.display = 'none'; el.style.display = '';
    const list = ARCHIVE.filter(x => x.ch === this.tab + 1);
    el.innerHTML = list.map((x, k) => {
      if (!s.archive.includes(x.id)) return `<div class="archItem locked"><span class="archSil">?</span><span class="archT">???</span><span class="archNum">${String(k + 1).padStart(2, '0')}</span></div>`;
      const isNew = !s.archiveSeen.includes(x.id);
      return `<div class="archItem found" data-id="${x.id}"><span class="archSil">${x.h ? '◉' : '●'}</span><span class="archT">${esc(x.t)}${x.h ? ' <i>HIDDEN</i>' : ''}${isNew ? ' <b>NEW</b>' : ''}</span><span class="archNum">${String(k + 1).padStart(2, '0')}</span></div>`;
    }).join('');
  }
  show(tab) {
    if (tab !== undefined) this.tab = tab; else { // open on the chapter with the newest unseen entry, else the current one
      const s = this.save, nu = ARCHIVE.find(e => s.archive.includes(e.id) && !s.archiveSeen.includes(e.id)); if (nu) this.tab = nu.ch - 1; }
    this.open = null; this.render(); const L = this.A.$('archList'); if (L) L.scrollTop = 0;
  }
  click(t) {
    const tb = t.closest && t.closest('.archTab'); if (tb) { this.tab = +tb.dataset.tab; this.open = null; this.render(); this.A.$('archList').scrollTop = 0; return; }
    if (t.closest && t.closest('.archBackList')) { const id = this.open; this.open = null; this.render(); const el = this.A.$('archList').querySelector(`.archItem[data-id="${id}"]`); if (el && el.scrollIntoView) el.scrollIntoView({ block: 'nearest' }); return; }
    const it = t.closest && t.closest('.archItem.found'); if (!it) return; const id = it.dataset.id;
    this.open = id; const s = this.save; if (!s.archiveSeen.includes(id)) { s.archiveSeen.push(id); this.A.writeSave(); }
    this.render();
  }
  back() { if (this.open) { this.click({ closest: (q) => q === '.archBackList' ? {} : null }); return true; } return false; }
}
